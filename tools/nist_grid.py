"""Download NIST WebBook (REFPROP) isotherms and generate a Rust Z(T,P) table."""
import subprocess, time, sys, os, hashlib

CACHE = os.path.join(os.environ.get("TEMP", "."), "nist_cache")
os.makedirs(CACHE, exist_ok=True)

R = 8.314462618
GASES = {
    "N2": ("C7727379", 28.0134e-3),
    "AR": ("C7440371", 39.948e-3),
    "HE": ("C7440597", 4.002602e-3),
    "NE": ("C7440019", 20.1797e-3),
    "CO2": ("C124389", 44.0095e-3),
}
TEMPS = [233.15 + 10 * i for i in range(12)]  # 233.15 .. 343.15 K
PRESS = [1.0] + [25.0 * i for i in range(1, 31)]  # 1, 25 .. 750 bar
CO2_PRESS = [1.0] + [5.0 * i for i in range(1, 15)]  # 1, 5 .. 70 bar


def fetch(gid, t, plow, phigh, pinc):
    url = (
        "https://webbook.nist.gov/cgi/fluid.cgi?Action=Data&Wide=on&ID=%s&Type=IsoTherm&Digits=6"
        "&T=%.2f&PLow=%g&PHigh=%g&PInc=%g&RefState=DEF&TUnit=K&PUnit=bar&DUnit=kg%%2Fm3"
        "&HUnit=kJ%%2Fkg&WUnit=m%%2Fs&VisUnit=uPa*s&STUnit=N%%2Fm" % (gid, t, plow, phigh, pinc)
    )
    key = os.path.join(CACHE, hashlib.sha1(url.encode()).hexdigest() + ".tsv")
    if os.path.exists(key):
        return open(key, encoding="utf-8").read()
    for attempt in range(8):
        try:
            out = subprocess.run(["curl", "-s", "--max-time", "60", url], capture_output=True, check=True)
            text = out.stdout.decode("utf-8")
            if text.startswith("Temperature"):
                open(key, "w", encoding="utf-8").write(text)
                return text
        except Exception as e:  # noqa: BLE001
            time.sleep(2 + attempt * 3)
    raise RuntimeError("download failed " + url)


def parse(text):
    rows = {}
    for line in text.splitlines()[1:]:
        c = line.split("\t")
        if len(c) < 14:
            continue
        p, rho, phase = float(c[1]), float(c[2]), c[13].strip()
        if phase == "liquid":
            continue
        rows.setdefault(round(p, 4), rho)
    return rows


out = []
out.append("//! Compressibility factors Z(T, P) generated from the NIST Chemistry WebBook")
out.append("//! (Lemmon, McLinden & Friend, REFPROP reference equations of state).")
out.append("//! Generated by tools/nist_grid.py — do not edit by hand.")
out.append("//! Z = P·M / (ρ·R·T); NaN marks liquid/unavailable points.")
out.append("")
out.append("/// Temperatures of the grid (K).")
out.append("pub const TEMPS: [f64; %d] = [%s];" % (len(TEMPS), ", ".join("%.2f" % t for t in TEMPS)))
out.append("/// Pressures of the grid for permanent gases (bar, absolute).")
out.append("pub const PRESS: [f64; %d] = [%s];" % (len(PRESS), ", ".join("%.1f" % p for p in PRESS)))
out.append("/// Pressures of the grid for CO₂ vapour (bar, absolute).")
out.append("pub const CO2_PRESS: [f64; %d] = [%s];" % (len(CO2_PRESS), ", ".join("%.1f" % p for p in CO2_PRESS)))

for name, (gid, m) in GASES.items():
    press = CO2_PRESS if name == "CO2" else PRESS
    table = []
    for t in TEMPS:
        if name == "CO2":
            rows = parse(fetch(gid, t, 1, 70, 5))
            rows.update(parse(fetch(gid, t, 5, 70, 5)))
        else:
            rows = parse(fetch(gid, t, 1, 751, 25))
            rows.update(parse(fetch(gid, t, 25, 750, 25)))
        line = []
        for p in press:
            rho = rows.get(round(p, 4))
            if rho is None:
                line.append("f64::NAN")
            else:
                z = p * 1e5 * m / (rho * R * t)
                line.append("%.6f" % z)
        table.append("    [" + ", ".join(line) + "],")
        print(name, t, file=sys.stderr)
        time.sleep(0.3)
    out.append("")
    out.append("/// Z table for %s, indexed [temperature][pressure]." % name)
    out.append("pub const Z_%s: [[f64; %d]; %d] = [" % (name, len(press), len(TEMPS)))
    out.extend(table)
    out.append("];")

open(sys.argv[1], "w", encoding="utf-8").write("\n".join(out) + "\n")
print("written", sys.argv[1], file=sys.stderr)
